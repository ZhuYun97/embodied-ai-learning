/**
 * 统计数据(build 时计算,暴露给组件渲染 meta/legend)
 */
export function computeStats(entries) {
  const benchmarks = [...new Set(entries.map((e) => e.benchmark))]
  const models = [...new Set(entries.map((e) => e.model))]
  const credibilityCount = {
    sourced: entries.filter((e) => e.credibility === 'sourced').length,
    self_reported: entries.filter((e) => e.credibility === 'self_reported').length,
    verified: entries.filter((e) => e.credibility === 'verified').length,
    unverified: entries.filter((e) => e.credibility === 'unverified').length,
  }
  return {
    total: entries.length,
    benchmarks: benchmarks.length,
    models: models.length,
    credibilityCount,
  }
}

// VitePress 数据加载器 default export
export default {
  watch: [],
  load() {
    const stats = computeStats(entries)
    console.log(
      `\n[leaderboard.data] 基准榜转录:${entries.length} 条 entry | ${stats.benchmarks} 基准 | ${stats.models} 模型 | 可信度分布:sourced ${stats.credibilityCount.sourced} / self_reported ${stats.credibilityCount.self_reported} / verified ${stats.credibilityCount.verified} / unverified ${stats.credibilityCount.unverified}`
    )
    return { entries, stats, SCHEMA }
  },
}
