/**
 * 统计数据(build 时计算,暴露给组件渲染 meta/legend)
 */
export function computeStats(entries) {
  const types = [...new Set(entries.map((e) => e.type))]
  const byType = {
    真机: entries.filter((e) => e.type === '真机').length,
    人类视频: entries.filter((e) => e.type === '人类视频').length,
    仿真环境: entries.filter((e) => e.type === '仿真环境').length,
    合成工具: entries.filter((e) => e.type === '合成工具').length,
  }
  const credibilityCount = {
    sourced: entries.filter((e) => e.credibility === 'sourced').length,
    self_reported: entries.filter((e) => e.credibility === 'self_reported').length,
    verified: entries.filter((e) => e.credibility === 'verified').length,
    unverified: entries.filter((e) => e.credibility === 'unverified').length,
  }
  return {
    total: entries.length,
    types: types.length,
    byType,
    credibilityCount,
  }
}

// VitePress 数据加载器 default export
export default {
  watch: [],
  load() {
    const stats = computeStats(entries)
    console.log(
      `\n[datasets.data] 数据集图鉴转录:${entries.length} 条 entry | 类型分布:真机 ${stats.byType.真机} / 人类视频 ${stats.byType.人类视频} / 仿真环境 ${stats.byType.仿真环境} / 合成工具 ${stats.byType.合成工具} | 可信度分布:sourced ${stats.credibilityCount.sourced} / self_reported ${stats.credibilityCount.self_reported} / verified ${stats.credibilityCount.verified} / unverified ${stats.credibilityCount.unverified}`
    )
    return { entries, stats, SCHEMA }
  },
}
